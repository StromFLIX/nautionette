import { test, expect } from '@playwright/test'
import { mockDesign } from './design-fixture.js'
import { PREFERENCES_KEY } from '../src/preferences-schema.js'

const palette = page => page.getByRole('dialog', { name: 'Search chats and settings', exact: true })
const search = page => palette(page).getByRole('combobox', { name: 'Search chats and settings' })
const message = page => page.getByRole('textbox', { name: 'Message', exact: true })

test('Cmd+K expands search from a composer, autofocuses, toggles, and preserves focus and drafts', async ({ page, context }) => {
  const state = await mockDesign(context)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/chats/alpha')
  await message(page).fill('Keep this draft')
  await page.keyboard.press('Meta+k')
  await expect(search(page)).toBeFocused()
  await expect(palette(page).locator('.q-dialog__inner')).not.toHaveClass(/--animating/)
  await expect(palette(page).getByRole('option', { name: 'Design review', exact: true })).toBeVisible()
  expect((await page.locator('.command-palette').boundingBox()).width).toBeGreaterThan(600)
  await page.keyboard.press('Meta+k')
  await expect(palette(page)).toHaveCount(0)
  await expect(message(page)).toBeFocused()
  await page.keyboard.press('Control+k')
  await expect(search(page)).toBeFocused()
  await search(page).fill('no-such-chat-or-setting')
  await expect(palette(page)).toContainText('No results')
  await page.keyboard.press('Enter')
  await expect(palette(page)).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(palette(page)).toHaveCount(0)
  await expect(message(page)).toBeFocused()
  await expect(message(page)).toHaveValue('Keep this draft')
  expect(state.sent).toEqual([])
  expect(state.writes).toEqual([])
  expect(errors).toEqual([])
})

test('sidebar search expands with its current query and finds chats even outside the activity filter', async ({ page, context }) => {
  const state = await mockDesign(context)
  await context.addInitScript(key => localStorage.setItem(key, JSON.stringify({ chatActiveMinutes: 60, chatKeepSelectedVisible: false })), PREFERENCES_KEY)
  state.data.chat.updated_at = Date.now() / 1000 - 86400 * 100
  await page.goto('/chats')
  const inlineSearch = page.getByRole('textbox', { name: 'Search chats', exact: true })
  await inlineSearch.fill('Design')
  await page.getByRole('button', { name: 'Expand chat search', exact: true }).click()
  await expect(search(page)).toHaveValue('Design')
  await expect(search(page)).toBeFocused()
  await expect(palette(page).locator('.q-dialog__inner')).not.toHaveClass(/--animating/)
  await page.screenshot({ path: '/tmp/nautionette-command-palette.png' })
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/chats\/alpha$/)
  await expect(palette(page)).toHaveCount(0)
  await expect(inlineSearch).toHaveValue('Design')
})

test('search works over settings and collapsed sidebars, with keyboard selection and deep links', async ({ page, context }) => {
  await mockDesign(context)
  await page.goto('/settings/general')
  await expect(page.getByRole('searchbox', { name: 'Search settings', exact: true })).toBeVisible()
  await page.keyboard.press('Control+k')
  await expect(search(page)).toBeFocused()
  // Result positions are not stable until asynchronous chat discovery has arrived.
  await expect(palette(page).getByRole('option', { name: 'Design review', exact: true })).toBeVisible()
  await expect(palette(page).locator('.q-dialog__inner')).not.toHaveClass(/--animating/)
  const first = palette(page).getByRole('option').first()
  await expect(first).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('ArrowDown')
  await expect(palette(page).getByRole('option').nth(1)).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('ArrowUp')
  await expect(first).toHaveAttribute('aria-selected', 'true')
  await palette(page).getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(search(page)).toBeFocused()
  await expect(palette(page).getByRole('option', { name: 'Design review', exact: true })).toHaveCount(0)
  await search(page).fill('visibility grace')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/settings\/workspace#chatSelectionGraceSeconds$/)
  await expect(page.locator('#chatSelectionGraceSeconds')).toBeFocused()
  await page.getByRole('button', { name: 'Back to workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click()
  await page.keyboard.press('Meta+k')
  await expect(search(page)).toBeFocused()
  await search(page).fill('Design')
  await palette(page).getByRole('option', { name: 'Design review', exact: true }).click()
  await expect(page).toHaveURL(/\/chats\/alpha$/)
  await expect(page.locator('#shell-sidebar')).toBeHidden()
})

test('late chat discovery preserves the keyboard-selected result rather than its old index', async ({ page, context }) => {
  await mockDesign(context)
  let releaseChats
  const discovered = new Promise(resolve => { releaseChats = resolve })
  await context.route('**/api/chats', async route => { await discovered; await route.fallback() })
  try {
    await page.goto('/settings/general')
    await expect(page.getByRole('searchbox', { name: 'Search settings', exact: true })).toBeVisible()
    await page.keyboard.press('Control+k')
    await expect(search(page)).toBeFocused()
    await expect(palette(page).locator('.q-dialog__inner')).not.toHaveClass(/--animating/)
    const next = palette(page).getByRole('option').nth(1)
    const name = await next.getAttribute('aria-label')
    await page.keyboard.press('ArrowDown')
    await expect(next).toHaveAttribute('aria-selected', 'true')
    releaseChats()
    await expect(palette(page).getByRole('option', { name: 'Design review', exact: true })).toBeVisible()
    await expect(palette(page).getByRole('option', { name, exact: true })).toHaveAttribute('aria-selected', 'true')
  } finally { releaseChats() }
})

test('palette follows the query, traps focus, and dismisses on outside click and mobile resize', async ({ page, context }) => {
  await mockDesign(context)
  await page.goto('/chats/alpha')
  await message(page).focus()
  await page.keyboard.press('Control+k')
  await expect(search(page)).toBeFocused()
  await page.keyboard.press('ArrowUp') // Last settings category; scrolling keeps it visible.
  const selected = palette(page).getByRole('option', { selected: true })
  await expect(selected).toBeInViewport()
  await search(page).fill('default model')
  await expect(palette(page).getByRole('option', { name: 'Default model', exact: true })).toHaveAttribute('aria-selected', 'true')
  const activeId = await search(page).getAttribute('aria-activedescendant')
  await expect(page.locator(`[id="${activeId}"]`)).toHaveAttribute('aria-selected', 'true')
  await expect(palette(page).locator('.q-dialog__inner')).not.toHaveClass(/--animating/)
  for (let i = 0; i < 7; i++) await page.keyboard.press('Tab')
  expect(await palette(page).evaluate(el => el.contains(document.activeElement))).toBe(true)
  await page.mouse.click(10, 10)
  await expect(palette(page)).toHaveCount(0)
  await expect(message(page)).toBeFocused()
  await page.keyboard.press('Control+k')
  await expect(search(page)).toBeFocused()
  await page.setViewportSize({ width: 900, height: 800 })
  await expect(palette(page)).toHaveCount(0)
  await page.keyboard.press('Control+k')
  await expect(palette(page)).toHaveCount(0)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(palette(page)).toHaveCount(0)
})

test('opening the current chat restores the composer and repeated keydown does not toggle the palette', async ({ page, context }) => {
  await mockDesign(context)
  await page.goto('/chats/alpha')
  await message(page).fill('Still writing')
  await page.keyboard.press('Control+k')
  await expect(search(page)).toBeFocused()
  await search(page).dispatchEvent('keydown', { key: 'k', ctrlKey: true, repeat: true })
  await expect(search(page)).toBeFocused()
  await search(page).fill('Design review')
  await page.keyboard.press('Enter')
  await expect(palette(page)).toHaveCount(0)
  await expect(message(page)).toBeFocused()
  await expect(message(page)).toHaveValue('Still writing')
})


"""Sync display branding into independently built services; never rename identity.

Edit branding/brand.json, logo.svg and fonts/, then run this script. Generated
copies are committed so each existing Docker build context stays self-contained.
CI uses --check; no runtime network requests or branding build service are needed.
"""

import argparse
import hashlib
import json
import re
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def validate_brand(brand: dict) -> None:
    name = brand.get("name")
    if (
        not isinstance(name, str)
        or not name.strip()
        or len(name) > 80
        or re.search(r"[<>/\\\\\x00-\x1f]", name)
    ):
        raise ValueError(
            "Brand name must be plain display text without path separators or control characters."
        )
    for key in ["tagline", "description", "interfaceFont", "defaultTheme", "repository"]:
        if not isinstance(brand.get(key), str) or not brand[key].strip():
            raise ValueError(f"Missing display brand field: {key}")
    for key in [
        "paper",
        "white",
        "ink",
        "muted",
        "line",
        "agent",
        "agentStrong",
        "session",
        "sessionStrong",
        "workflow",
        "workflowStrong",
    ]:
        value = brand.get("colors", {}).get(key)
        if not isinstance(value, str) or not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
            raise ValueError(f"Brand color {key} must be a six-digit hex color.")


def expected_files(root: Path = ROOT) -> dict[Path, bytes]:
    source = root / "branding"
    brand = json.loads((source / "brand.json").read_text())
    validate_brand(brand)
    logo = (source / "logo.svg").read_bytes()
    logo_version = hashlib.sha256(logo).hexdigest()[:12]
    manifest_data = {**brand, "logoVersion": logo_version}
    manifest = (json.dumps(manifest_data, ensure_ascii=False, indent=2) + "\n").encode()
    favicon = (
        logo.decode()
        .replace(
            "</svg>",
            '<style>@media(prefers-color-scheme:dark){path[fill="#000000"]{fill:#fff}'
            'path[stroke="#000000"]{stroke:#fff}}</style>\n</svg>',
        )
        .encode()
    )
    frontend = root / "services/frontend"
    website = root / "services/website"
    files = {
        frontend / "public/brand/brand.json": manifest,
        frontend / "src/brand-data.json": manifest,
        frontend / "desktop/brand.json": manifest,
        root / "images/pi-base/brand.json": manifest,
        root / "images/agent-sets/default/extensions/nautionette/brand.json": manifest,
        frontend / "public/brand/logo.svg": logo,
        frontend / "public/favicon.svg": favicon,
        website / "assets/denkzeug-icon.svg": logo,
        website / "favicon.svg": favicon,
        website / "brand.mjs": (
            "// Generated by scripts/sync_brand.py; edit branding/brand.json.\n"
            + "export const brand = Object.freeze("
            + manifest.decode().strip()
            + ")\n"
        ).encode(),
        root / "libs/nautionette/src/nautionette/brand.py": (
            '"""Generated display branding. Technical namespaces remain unchanged."""\n\n'
            + f"NAME = {json.dumps(brand['name'], ensure_ascii=False)}\n"
            + f"TAGLINE = {json.dumps(brand['tagline'], ensure_ascii=False)}\n"
            + f"DESCRIPTION = {json.dumps(brand['description'], ensure_ascii=False)}\n"
        ).encode(),
    }
    for font in sorted((source / "fonts").iterdir()):
        files[frontend / "public/brand/fonts" / font.name] = font.read_bytes()
        files[website / "assets/fonts" / font.name] = font.read_bytes()
    native = source / "native"
    if native.exists():
        if (native / "source.sha256").read_text().strip() != hashlib.sha256(logo).hexdigest():
            raise ValueError(
                "Refresh native icon exports and branding/native/source.sha256 for the new logo."
            )
        for name in ["app-icon.svg", "app-icon.png", "ic_launcher.png", "ic_launcher_foreground.png"]:
            files[frontend / "native/icons" / name] = (native / name).read_bytes()
        for destination in ["build/icon.png", "desktop/icon.png", "public/brand/app-icon.png"]:
            files[frontend / destination] = (native / "app-icon.png").read_bytes()
    for design in sorted((frontend / "src/skin-examples").glob("*.skin.json")):
        text = re.sub(
            r'("author"\s*:\s*)"[^"]*"',
            lambda match: match[1] + json.dumps(brand["name"]),
            design.read_text(),
        )
        files[design] = text.encode()
    tokens = {
        "paper": "paper",
        "white": "white",
        "ink": "ink",
        "muted": "muted",
        "line": "line",
        "agent": "agent",
        "session": "session",
        "workflow": "workflow",
    }
    files[website / "brand.css"] = (
        "/* Generated by scripts/sync_brand.py. */\n:root {\n"
        + "".join(f"  --{key}: {brand['colors'][value]};\n" for key, value in tokens.items())
        + "}\n"
    ).encode()
    files[frontend / "src/styles/brand.css"] = (
        "/* Generated by scripts/sync_brand.py. */\n"
        + "@font-face { font-family: Sora; src: url('/brand/fonts/Sora.woff2') format('woff2'); "
        "font-style: normal; font-weight: 100 800; font-display: swap; }\n"
        + "@font-face { font-family: 'Source Serif'; "
        "src: url('/brand/fonts/SourceSerif4.woff2') format('woff2'); "
        "font-style: normal; font-weight: 200 900; font-display: swap; }\n"
        + ":root {\n"
        + "".join(f"  --brand-{key}: {value};\n" for key, value in brand["colors"].items())
        + "}\n"
    ).encode()
    agent_template = root / "images/agent-sets/default/AGENTS.template.md"
    if agent_template.exists():
        files[root / "images/agent-sets/default/AGENTS.md"] = (
            agent_template.read_text().replace("{{brand.name}}", brand["name"]).encode()
        )
    release_workflow = root / "workflows/prepare_nautionette_release.py"
    if release_workflow.exists():
        text = re.sub(
            r'^DISPLAY_NAME = "[^"]*"',
            lambda _: "DISPLAY_NAME = " + json.dumps(brand["name"]),
            release_workflow.read_text(),
            flags=re.MULTILINE,
        )
        text = re.sub(
            r'("title"\s*:\s*)"Prepare [^"]* release"',
            lambda match: match[1] + json.dumps(f"Prepare {brand['name']} release"),
            text,
        )
        files[release_workflow] = text.encode()
    template = website / "index.template.html"
    if template.exists():
        html = template.read_text()
        for key in ["name", "tagline", "description"]:
            html = html.replace("{{brand." + key + "}}", escape(brand[key], quote=True))
        html = html.replace('"/assets/denkzeug-icon.svg"', f'"/assets/denkzeug-icon.svg?v={logo_version}"')
        html = re.sub(r'href="/favicon\.svg(?:\?[^"]*)?"', f'href="/favicon.svg?v={logo_version}"', html)
        files[website / "index.html"] = html.encode()
    index = frontend / "index.html"
    html = index.read_text()
    html = re.sub(r"<title>[^<]*</title>", f"<title>{escape(brand['name'])}</title>", html)
    html = re.sub(
        r'(<meta name="theme-color" content=")[^"]*(" />)', rf"\g<1>{brand['colors']['paper']}\2", html
    )
    html = re.sub(r'href="/favicon\.svg(?:\?[^"]*)?"', f'href="/favicon.svg?v={logo_version}"', html)
    files[index] = html.encode()
    # Display metadata only: preserve appId, package name, protocol schemes,
    # artifact names, desktopName, data paths and the existing updater identity.
    package = frontend / "package.json"
    text = package.read_text()
    for key, value in {
        "description": f"{brand['name']} desktop and mobile client for your self-hosted instance",
        "author": f"{brand['name']} contributors",
        "productName": brand["name"],
        "NSMicrophoneUsageDescription": f"Record dictation for your {brand['name']} instance.",
    }.items():
        text = re.sub(
            rf'("{key}"\s*:\s*)"(?:[^"\\]|\\.)*"', lambda m, value=value: m[1] + json.dumps(value), text
        )
    text = re.sub(
        r'("protocols"\s*:\s*\[\s*\{\s*"name"\s*:\s*)"[^"]*"',
        lambda m: m[1] + json.dumps(brand["name"] + " return"),
        text,
    )
    files[package] = text.encode()
    capacitor = frontend / "capacitor.config.json"
    text = re.sub(
        r'("appName"\s*:\s*)"[^"]*"', lambda m: m[1] + json.dumps(brand["name"]), capacitor.read_text()
    )
    files[capacitor] = text.encode()
    return files


def sync(check: bool = False, root: Path = ROOT) -> list[str]:
    changed = []
    for path, content in expected_files(root).items():
        if path.exists() and path.read_bytes() == content:
            continue
        changed.append(str(path.relative_to(root)))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    return changed


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on stale copies without writing")
    args = parser.parse_args()
    changed = sync(args.check)
    if changed:
        print(("Stale branding copies:\n" if args.check else "Updated branding:\n") + "\n".join(changed))
    else:
        print("Branding copies match their canonical sources.")
    sys.exit(1 if changed and args.check else 0)
